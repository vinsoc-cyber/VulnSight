"""The generator writes Python that the running server imports.

modules/cwe_catalog.py is generated by tools/generate_cwe_catalog.py and
imported by modules/cwe_categories.py, which every source client imports in
turn -- so whatever this script emits is executed inside the server at
startup. Nothing checked that before: no test rendered the module, no test
compiled it, and the only thing standing between a tampered or malformed
MITRE XML and arbitrary code in the gunicorn process was that the real file
happens to be well behaved.
"""

import os
import sys
import unittest
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))

import generate_cwe_catalog as gen

NS = "http://cwe.mitre.org/cwe-7"


def _xml(version="4.20", date="2026-04-30", weaknesses=()):
    """A minimal catalog in the shape collect() expects.

    Built as an element tree rather than by string interpolation: the point of
    these tests is to feed render() attribute values containing quotes, and
    interpolating those into XML text would break the XML before the code
    under test ever saw them.
    """
    root = ET.Element(f"{{{NS}}}Weakness_Catalog", {"Version": version, "Date": date})
    container = ET.SubElement(root, f"{{{NS}}}Weaknesses")
    for cwe_id, name, status, terms in weaknesses:
        weakness = ET.SubElement(container, f"{{{NS}}}Weakness", {
            "ID": cwe_id, "Name": name, "Status": status, "Abstraction": "Base"})
        if terms:
            alt = ET.SubElement(weakness, f"{{{NS}}}Alternate_Terms")
            for term in terms:
                node = ET.SubElement(alt, f"{{{NS}}}Alternate_Term")
                ET.SubElement(node, f"{{{NS}}}Term").text = term
    return root


def _module_from(root):
    """render() the catalog and execute it, as the server's import would."""
    text = gen.render(root)
    compile(text, "<generated>", "exec")          # must be valid Python
    namespace: dict = {}
    exec(compile(text, "<generated>", "exec"), namespace)
    return text, namespace


class TestGeneratedModuleIsValid(unittest.TestCase):
    def setUp(self):
        self._saved_extra = dict(gen.EXTRA_ALIASES)
        gen.EXTRA_ALIASES.clear()

    def tearDown(self):
        gen.EXTRA_ALIASES.clear()
        gen.EXTRA_ALIASES.update(self._saved_extra)

    def test_a_normal_catalog_renders_a_usable_module(self):
        root = _xml(weaknesses=[
            ("79", "Cross-site Scripting", "Stable", ["XSS"]),
            ("639", "Authorization Bypass Through User-Controlled Key",
             "Stable", ["Insecure Direct Object Reference / IDOR"]),
            ("1", "DEPRECATED: Location", "Deprecated", []),
        ])
        _, ns = _module_from(root)
        self.assertEqual(ns["CWE_VERSION"], "4.20")
        self.assertEqual(ns["CWE_RELEASED"], "2026-04-30")
        self.assertEqual(ns["NAMES"]["79"], "Cross-site Scripting")
        self.assertIn("XSS", ns["ALIASES"]["79"])
        # "Insecure Direct Object Reference / IDOR" splits into both halves.
        self.assertIn("IDOR", ns["ALIASES"]["639"])
        self.assertIn("Insecure Direct Object Reference", ns["ALIASES"]["639"])
        # Deprecated ids keep a name (old advisory tags still render) but are
        # excluded from the picker.
        self.assertIn("1", ns["NAMES"])
        self.assertIn("1", ns["DEPRECATED"])
        self.assertNotIn("1", ns["ALIASES"])

    def test_an_abstraction_level_with_no_members_still_compiles(self):
        """It emitted "(,)" -- a SyntaxError -- and main() wrote the file
        before anything checked, so the next start failed to import."""
        root = _xml(weaknesses=[("79", "Cross-site Scripting", "Stable", [])])
        _, ns = _module_from(root)
        self.assertEqual(set(ns["ABSTRACTION"]), set(gen.ABSTRACTIONS))
        self.assertEqual(
            sum(len(v) for v in ns["ABSTRACTION"].values()), 1)

    def test_a_hostile_version_attribute_is_refused(self):
        """Version and Date reach the generated file outside a repr(): they
        are also interpolated into its module docstring, where a value
        containing a triple quote closes the docstring and executes the rest
        on import. repr() cannot defend that, so they are validated instead,
        and anything that is not a plain version string is refused."""
        payload = '4.20"""\nimport os\nos.environ["PWNED"] = "1"\n_X = """'
        with self.assertRaises(SystemExit):
            gen.render(_xml(version=payload, weaknesses=[
                ("79", "Cross-site Scripting", "Stable", [])]))
        self.assertNotIn("PWNED", os.environ)

    def test_a_quote_bearing_version_is_refused(self):
        payload = '4.20"; import os; os.environ["PWNED2"] = "1"; _X = "'
        with self.assertRaises(SystemExit):
            gen.render(_xml(version=payload, weaknesses=[
                ("79", "Cross-site Scripting", "Stable", [])]))
        self.assertNotIn("PWNED2", os.environ)

    def test_a_hostile_date_attribute_is_refused(self):
        with self.assertRaises(SystemExit):
            gen.render(_xml(date='2026-01-01"; _Y = "', weaknesses=[
                ("79", "Cross-site Scripting", "Stable", [])]))

    def test_an_ordinary_version_and_date_still_pass(self):
        _, ns = _module_from(_xml(version="4.20", date="2026-04-30", weaknesses=[
            ("79", "Cross-site Scripting", "Stable", [])]))
        self.assertEqual(ns["CWE_VERSION"], "4.20")
        self.assertEqual(ns["CWE_RELEASED"], "2026-04-30")

    def test_a_hostile_weakness_name_stays_data(self):
        root = _xml(weaknesses=[
            ("79", 'Name", "9999": "injected', "Stable", []),
        ])
        _, ns = _module_from(root)
        self.assertNotIn("9999", ns["NAMES"])
        # And the weakness survived as data rather than being dropped:
        # asserting only absence passes if render silently lost the row.
        self.assertEqual(ns["NAMES"]["79"], 'Name", "9999": "injected')

    def test_render_is_deterministic(self):
        """docs/cwe-catalog.md promises byte-identical output for the same
        input, which is what makes a drift check possible at all."""
        root = _xml(weaknesses=[
            ("639", "Authorization Bypass", "Stable", ["IDOR"]),
            ("79", "Cross-site Scripting", "Stable", ["XSS"]),
        ])
        self.assertEqual(gen.render(root), gen.render(root))

    def test_ids_are_sorted_numerically_not_lexicographically(self):
        root = _xml(weaknesses=[
            ("100", "Hundred", "Stable", []),
            ("9", "Nine", "Stable", []),
            ("20", "Twenty", "Stable", []),
        ])
        _, ns = _module_from(root)
        self.assertEqual(list(ns["NAMES"]), ["9", "20", "100"])


class TestTheCommittedCatalogMatchesItsGenerator(unittest.TestCase):
    """The checked-in module must still look like generator output.

    The real MITRE XML is not in the repo, so this cannot re-render it. What
    it can do is hold the committed file to the invariants render() produces,
    which is what would catch a hand-edit -- something the file's own header
    forbids and nothing enforced.
    """

    def setUp(self):
        from modules import cwe_catalog
        self.catalog = cwe_catalog

    def test_names_are_sorted_numerically(self):
        ids = [int(i) for i in self.catalog.NAMES]
        self.assertEqual(ids, sorted(ids))

    def test_aliases_and_abstraction_only_reference_known_ids(self):
        known = set(self.catalog.NAMES)
        self.assertEqual(set(self.catalog.ALIASES) - known, set())
        for level, ids in self.catalog.ABSTRACTION.items():
            self.assertEqual(set(ids) - known, set(), level)

    def test_deprecated_ids_are_excluded_from_aliases_and_abstraction(self):
        deprecated = set(self.catalog.DEPRECATED)
        self.assertEqual(deprecated & set(self.catalog.ALIASES), set())
        for level, ids in self.catalog.ABSTRACTION.items():
            self.assertEqual(deprecated & set(ids), set(), level)

    def test_every_non_deprecated_id_has_an_abstraction_level(self):
        placed = {i for ids in self.catalog.ABSTRACTION.values() for i in ids}
        unplaced = set(self.catalog.NAMES) - placed - set(self.catalog.DEPRECATED)
        self.assertEqual(unplaced, set())

    def test_abstraction_keys_are_exactly_the_generators_levels(self):
        self.assertEqual(list(self.catalog.ABSTRACTION), list(gen.ABSTRACTIONS))

    def test_every_extra_alias_survived_into_the_catalog(self):
        for cwe_id, terms in gen.EXTRA_ALIASES.items():
            self.assertIn(cwe_id, self.catalog.NAMES, cwe_id)
            if cwe_id in self.catalog.DEPRECATED:
                continue
            present = {t.lower() for t in self.catalog.ALIASES.get(cwe_id, ())}
            name = self.catalog.NAMES[cwe_id].lower()
            for term in terms:
                self.assertTrue(
                    term.lower() in present or term.lower() in name,
                    f"EXTRA_ALIASES[{cwe_id}] lost {term!r}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
